"""Microcontroller deployment: lookup-table policies and a hardware-in-the-loop sim.

A trained policy (any of them: DDPG, SAC, PIRL, ...) is sampled on a
(theta, omega) grid and quantised to int8.  The table lives in ESP32 flash, so
inference is one bilinear lookup with no matrix multiplies.

`HardwareLoop` simulates what the real rig adds on top of the ideal plant:
  * quadrature encoder quantisation (CPR counts / rev)
  * velocity from a finite difference + EMA filter, as in the firmware
  * one-sample computation/actuation delay
  * PWM resolution (8-bit duty)
This lets us check, before flashing, that the LUT policy still swings up.
"""
import math

import numpy as np

from .controllers.classical import Policy
from .systems import rk4_step, wrap


def build_lut(policy, n_th=128, n_w=64, w_lim=12.0):
    th = np.linspace(-math.pi, math.pi, n_th, endpoint=False)
    w = np.linspace(-w_lim, w_lim, n_w)
    TH, W = np.meshgrid(th, w, indexing="ij")
    U = policy(np.stack([TH.ravel(), W.ravel()], -1)).reshape(n_th, n_w)
    q = np.clip(np.round(U * 127), -127, 127).astype(np.int8)
    return {"lut": q, "n_th": n_th, "n_w": n_w, "w_lim": w_lim}


class LUTPolicy(Policy):
    """Bilinear interpolation in the int8 table: the same arithmetic as the firmware."""

    def __init__(self, table, name="LUT"):
        self.t, self.name = table, name
        self.lut = table["lut"].astype(np.float64) / 127.0

    def act(self, X):
        n_th, n_w, wl = self.t["n_th"], self.t["n_w"], self.t["w_lim"]
        ti = (wrap(X[:, 0]) + math.pi) / (2 * math.pi) * n_th
        wi = np.clip((X[:, 1] + wl) / (2 * wl) * (n_w - 1), 0, n_w - 1 - 1e-9)
        t0 = np.floor(ti).astype(int); ft = ti - t0; t0 %= n_th; t1 = (t0 + 1) % n_th
        w0 = np.floor(wi).astype(int); fw = wi - w0; w1 = np.minimum(w0 + 1, n_w - 1)
        L = self.lut
        u = ((1 - ft) * (1 - fw) * L[t0, w0] + ft * (1 - fw) * L[t1, w0]
             + (1 - ft) * fw * L[t0, w1] + ft * fw * L[t1, w1])
        return u[:, None]


def hardware_rollout(sys, policy, X0, T=10.0, cpr=2400, ema_alpha=0.35, delay=1, pwm_bits=8,
                     torque_noise=0.0, seed=0):
    """Closed loop with encoder quantisation, EMA velocity, delay and PWM quantisation."""
    rng = np.random.default_rng(seed)
    steps = int(T / sys.dt)
    X = np.array(X0, dtype=np.float64)
    N = len(X)
    res = 2 * math.pi / cpr
    counts = np.round(X[:, 0] / res)
    w_hat = np.zeros(N)
    u_queue = [np.zeros((N, 1))] * delay
    pwm_levels = 2 ** (pwm_bits - 1) - 1
    xs, us = [X.copy()], []
    for k in range(steps):
        new_counts = np.round(X[:, 0] / res)
        dtheta = wrap((new_counts - counts) * res)
        counts = new_counts
        w_hat = ema_alpha * (dtheta / sys.dt) + (1 - ema_alpha) * w_hat
        obs = np.stack([wrap(counts * res), w_hat], -1)
        u_cmd = np.round(np.clip(policy(obs), -1, 1) * pwm_levels) / pwm_levels
        u_queue.append(u_cmd)
        u = u_queue.pop(0)
        if torque_noise:
            u = np.clip(u + rng.normal(0, torque_noise, u.shape), -1, 1)
        X = rk4_step(sys, X, u)
        X[:, 0] = wrap(X[:, 0])
        xs.append(X.copy()); us.append(u)
    return {"x": np.stack(xs, 1), "u": np.stack(us, 1), "dt": sys.dt,
            "c": np.stack([sys.cost(xs[i], us[i]) * sys.dt for i in range(steps)], 1),
            "alive": np.ones(N, bool), "wall": 0.0}


def export_header(table, path, source_name):
    lut = table["lut"]
    n_th, n_w = lut.shape
    with open(path, "w") as f:
        f.write(f"// Auto-generated by pirl/deploy.py from policy: {source_name}\n")
        f.write("// u = POLICY_LUT[i_theta][i_omega] / 127  (normalised motor voltage, +-1 = full PWM)\n")
        f.write("// theta in [-pi, pi) (0 = upright), periodic;  omega in [-W_LIM, W_LIM] rad/s, clamped\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define LUT_N_TH {n_th}\n#define LUT_N_W {n_w}\n#define LUT_W_LIM {table['w_lim']:.4f}f\n\n")
        f.write(f"// {n_th * n_w} bytes; 'const' places it in flash on the ESP32\n")
        f.write(f"static const int8_t POLICY_LUT[LUT_N_TH][LUT_N_W] = {{\n")
        for i in range(n_th):
            f.write("  {" + ",".join(str(int(v)) for v in lut[i]) + "},\n")
        f.write("};\n")
